export type Translate = (key: Key, vars?: {[name: string]: string | number}) => string;

export function makeTranslate(hass: any): Translate {
    const language = String(hass?.locale?.language ?? hass?.language ?? "en").toLowerCase();
    const texts = language.startsWith("de") ? DE : EN;
    return (key, vars = {}) => {
        const text = texts[key] ?? EN[key] ?? key;
        return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : ""));
    };
}
